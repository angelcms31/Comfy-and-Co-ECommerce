-- Comfy&Co tables, following the ERD.
-- Run this first in the Supabase SQL Editor, then seed.sql.
--
-- "user" and "order" are reserved words in Postgres, so they always need double quotes.

create table user_role (
  user_role_id  int generated by default as identity primary key,
  user_role     text not null unique check (user_role in ('customer', 'admin')),
  date_added    timestamptz not null default now()
);

create table country (
  country_id  int generated by default as identity primary key,
  country     text not null unique,
  date_added  timestamptz not null default now()
);

create table city (
  city_id     int generated by default as identity primary key,
  country_id  int not null references country (country_id),
  city        text not null,
  date_added  timestamptz not null default now()
);

-- user_id is the same id as the Supabase Auth user
create table "user" (
  user_id       uuid primary key references auth.users (id) on delete cascade,
  user_role_id  int not null default 1 references user_role (user_role_id),
  full_name     text not null,
  birthdate     date,
  email         text not null unique,
  mobile_no     text,
  st_add        text,
  postal        text,
  city_id       int references city (city_id),
  date_added    timestamptz not null default now()
);

create table item_categ (
  item_categ_id  int generated by default as identity primary key,
  item_category  text not null unique,
  date_added     timestamptz not null default now()
);

create table product (
  product_id     int generated by default as identity primary key,
  item_categ_id  int not null references item_categ (item_categ_id),
  product_name   text not null,
  prod_desc      text,
  is_avail       boolean not null default true
);

-- images: comma-separated image URLs
create table prod_var (
  prod_var_id    int generated by default as identity primary key,
  product_id     int not null references product (product_id) on delete cascade,
  sku            text not null unique,
  prod_var_name  text not null,
  prod_attr      text,
  b_price        numeric(10, 2) not null check (b_price >= 0),
  pr_price       numeric(10, 2) check (pr_price >= 0),
  pr_start       date,
  pr_end         date,
  stocks         int not null default 0 check (stocks >= 0),
  is_avail       boolean not null default true,
  images         text,
  date_added     timestamptz not null default now()
);

create table review (
  review_id    int generated by default as identity primary key,
  user_id      uuid not null references "user" (user_id) on delete cascade,
  prod_var_id  int not null references prod_var (prod_var_id) on delete cascade,
  rating       smallint not null check (rating between 1 and 5),
  content      text
);

create table wishlist_col (
  wishlist_coll_id  int generated by default as identity primary key,
  user_id           uuid not null references "user" (user_id) on delete cascade,
  created_at        timestamptz not null default now()
);

create table wishlist_item (
  wishlist_item_id  int generated by default as identity primary key,
  wishlist_coll_id  int not null references wishlist_col (wishlist_coll_id) on delete cascade,
  prod_var_id       int not null references prod_var (prod_var_id) on delete cascade,
  created_at        timestamptz not null default now(),
  unique (wishlist_coll_id, prod_var_id)
);

create table cart (
  cart_id     int generated by default as identity primary key,
  user_id     uuid not null unique references "user" (user_id) on delete cascade,
  created_at  timestamptz not null default now()
);

create table cart_item (
  cart_item_id  int generated by default as identity primary key,
  cart_id       int not null references cart (cart_id) on delete cascade,
  prod_var_id   int not null references prod_var (prod_var_id) on delete cascade,
  quantity      int not null check (quantity > 0),
  unique (cart_id, prod_var_id)
);

create table "order" (
  order_id        int generated by default as identity primary key,
  order_num       text not null unique,
  user_id         uuid not null references "user" (user_id),
  order_stat      text not null default 'Pending' check (order_stat in ('Pending', 'Shipped', 'Delivered', 'Cancelled')),
  subtotal        numeric(10, 2) not null,
  disc_amt        numeric(10, 2) not null default 0,
  total_amt       numeric(10, 2) not null,
  payment_method  text not null check (payment_method in ('GCash', 'COD')),
  shipping_add    text not null,
  placed_at       timestamptz not null default now()
);

-- prod_var_id is kept even if the variant is deleted later, item_name/item_price are the snapshot
create table order_item (
  order_item_id  int generated by default as identity primary key,
  order_id       int not null references "order" (order_id) on delete cascade,
  prod_var_id    int references prod_var (prod_var_id) on delete set null,
  item_name      text not null,
  item_price     numeric(10, 2) not null,
  quantity       int not null check (quantity > 0),
  sub_total      numeric(10, 2) not null
);

create index on city (country_id);
create index on product (item_categ_id);
create index on prod_var (product_id);
create index on review (prod_var_id);
create index on wishlist_item (prod_var_id);
create index on cart_item (prod_var_id);
create index on "order" (user_id);
create index on "order" (placed_at);
create index on order_item (order_id);

-- FastAPI connects with the service role key, so the tables are locked from the public anon key.
alter table user_role enable row level security;
alter table country enable row level security;
alter table city enable row level security;
alter table "user" enable row level security;
alter table item_categ enable row level security;
alter table product enable row level security;
alter table prod_var enable row level security;
alter table review enable row level security;
alter table wishlist_col enable row level security;
alter table wishlist_item enable row level security;
alter table cart enable row level security;
alter table cart_item enable row level security;
alter table "order" enable row level security;
alter table order_item enable row level security;
