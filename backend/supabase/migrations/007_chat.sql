-- Chat between customers and the store. A bot answers common questions, and the customer can ask for a staff member.
-- One thread per customer. Only the backend reads and writes these tables. Safe to run more than once.
create table if not exists chat_thread (
  thread_id         bigint generated by default as identity primary key,
  user_id           uuid not null unique references "user" (user_id) on delete cascade,
  needs_staff       boolean not null default false,          -- true once the customer asks for staff, until an admin marks it resolved
  last_message_at   timestamptz not null default now(),
  customer_read_at  timestamptz not null default now(),       -- unread counts: messages newer than these
  admin_read_at     timestamptz not null default now(),
  created_at        timestamptz not null default now()
);
create index if not exists chat_thread_last_message_idx on chat_thread (last_message_at desc);

create table if not exists chat_message (
  message_id  bigint generated by default as identity primary key,
  thread_id   bigint not null references chat_thread (thread_id) on delete cascade,
  sender      text not null check (sender in ('customer', 'bot', 'admin')),
  admin_id    uuid references "user" (user_id) on delete set null,  -- who replied, when sender = 'admin'
  body        text not null,
  created_at  timestamptz not null default now()
);
create index if not exists chat_message_thread_idx on chat_message (thread_id, created_at);

alter table chat_thread enable row level security;
alter table chat_message enable row level security;
