-- Admin panel: Super Admin role, deactivated admins, review replies / features / photos, audit log, store settings.
-- Not in the ERD yet, see SCHEMA_GAPS.md #24-28. Safe to run more than once.

-- Super Admin manages the other admins and the settings; Admin runs the shop
alter table user_role drop constraint if exists user_role_user_role_check;
alter table user_role add constraint user_role_user_role_check check (user_role in ('customer', 'admin', 'super_admin'));
insert into user_role (user_role) values ('super_admin') on conflict (user_role) do nothing;

-- when a Super Admin deactivated this account (the login itself is banned in Supabase Auth)
alter table "user" add column if not exists deactivated_at timestamptz;

alter table review
  add column if not exists created_at  timestamptz not null default now(),
  add column if not exists photos      text,                              -- comma separated URLs, like prod_var.images
  add column if not exists reply       text,                              -- the store's answer
  add column if not exists replied_at  timestamptz,
  add column if not exists is_featured boolean not null default false,
  add column if not exists is_hidden   boolean not null default false;

-- every change an admin makes (products, orders, reviews, admins, settings)
create table if not exists audit_log (
  log_id      bigint generated by default as identity primary key,
  user_id     uuid references "user" (user_id) on delete set null,
  action      text not null,
  ip_address  text,
  device      text,
  created_at  timestamptz not null default now()
);
create index if not exists audit_log_created_at_idx on audit_log (created_at desc);

-- one row per setting, value is JSON (store info, policies, security)
create table if not exists store_setting (
  key         text primary key,
  value       jsonb not null,
  updated_at  timestamptz not null default now()
);

alter table audit_log enable row level security;
alter table store_setting enable row level security;
