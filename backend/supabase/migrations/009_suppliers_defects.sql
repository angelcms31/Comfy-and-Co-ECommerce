-- Suppliers and defective item tracking. Safe to run more than once.
--
-- Each category has one supplier; every product in it comes from that supplier.
-- A defect report saves the supplier at the time it's reported, so changing a category's supplier later
-- doesn't move old defects to the new supplier.

create table if not exists supplier (
  supplier_id     int generated by default as identity primary key,
  supplier_name   text not null unique,
  contact_person  text,
  phone           text,
  email           text,
  address         text,
  is_active       boolean not null default true,
  created_at      timestamptz not null default now()
);

alter table item_categ add column if not exists supplier_id int references supplier (supplier_id) on delete set null;

-- source: where the defect was found
--   receiving        when the supplier's delivery arrived (never added to stock)
--   storage          found while already in stock (taken out of stock when reported)
--   customer_return  sent back by a customer through a refund request
-- status: Reported -> Returned to supplier -> Replaced (the new units go back into stock) or Credited
--         Reported -> Credited also works when the supplier credits without taking the item back
create table if not exists defect_report (
  defect_id      int generated by default as identity primary key,
  prod_var_id    int references prod_var (prod_var_id) on delete set null,
  item_name      text not null,                       -- product + variant name, kept if the product is deleted
  sku            text not null,
  supplier_id    int references supplier (supplier_id) on delete set null,
  supplier_name  text,                                -- null when the category had no supplier yet
  quantity       int not null check (quantity > 0),
  defect_type    text not null,
  source         text not null check (source in ('receiving', 'storage', 'customer_return')),
  order_id       int references "order" (order_id) on delete set null,  -- the customer's order, for customer returns
  notes          text,
  photos         text,                                -- comma separated URLs, like prod_var.images
  status         text not null default 'Reported' check (status in ('Reported', 'Returned to supplier', 'Replaced', 'Credited')),
  reported_by    uuid references "user" (user_id) on delete set null,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index if not exists defect_report_supplier_idx on defect_report (supplier_id);
create index if not exists defect_report_created_idx on defect_report (created_at desc);

alter table supplier enable row level security;
alter table defect_report enable row level security;
