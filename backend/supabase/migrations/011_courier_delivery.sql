-- Lalamove delivery. Safe to run more than once.
--
-- Every delivery is one Lalamove booking. The vehicle is picked from the size and weight of the items in the order
-- (app/delivery.py), the fee from the vehicle's rate card in Settings > Delivery and the road distance from the store.
-- When an admin marks the order Shipped, a secret token is made for the QR code on the printed receipt: the rider scans it
-- at the customer's door, takes 1-3 photos and the order becomes Delivered (routers/delivery.py, no login needed).

-- size and weight of each variant, for picking the Lalamove vehicle. Filled from products.json by supabase/load_dimensions.py
alter table prod_var add column if not exists length_cm numeric(6, 1) check (length_cm > 0);
alter table prod_var add column if not exists width_cm  numeric(6, 1) check (width_cm > 0);
alter table prod_var add column if not exists height_cm numeric(6, 1) check (height_cm > 0);
alter table prod_var add column if not exists weight_kg numeric(7, 2) check (weight_kg > 0);

-- where the customer pinned their house on the map (optional, the typed address is geocoded when there's no pin) and notes for the rider
alter table "user" add column if not exists lat double precision;
alter table "user" add column if not exists lng double precision;
alter table "user" add column if not exists delivery_note text;

alter table "order" add column if not exists courier        text;                          -- 'Lalamove', null for store pickup
alter table "order" add column if not exists vehicle        text;                          -- Lalamove vehicle picked for the order, e.g. 'MPV 600 kg'
alter table "order" add column if not exists trips          int not null default 1;        -- more than 1 when the order doesn't fit the largest vehicle
alter table "order" add column if not exists distance_km    numeric(6, 1);                 -- road distance from the store
alter table "order" add column if not exists delivery_fee   numeric(10, 2) not null default 0;
alter table "order" add column if not exists drop_lat       double precision;
alter table "order" add column if not exists drop_lng       double precision;
alter table "order" add column if not exists delivery_note  text;
alter table "order" add column if not exists delivery_token text unique;                   -- in the receipt's QR code, made when the order ships
alter table "order" add column if not exists delivered_at   timestamptz;
alter table "order" add column if not exists delivered_by   text check (delivered_by in ('rider', 'customer', 'admin'));
alter table "order" add column if not exists proof_photos   text;                          -- comma separated URLs, like refund.photos
-- after the rider marks it delivered the customer answers "did you get it?": one of these two is filled
alter table "order" add column if not exists receipt_confirmed_at timestamptz;                -- yes, received
alter table "order" add column if not exists not_received_report  text;                       -- no: what the customer says happened
alter table "order" add column if not exists not_received_at      timestamptz;

-- Returned: the rider couldn't deliver it MAX_DELIVERY_ATTEMPTS times (or an admin set it), the package is back at the store and the stock is put back
alter table "order" drop constraint if exists order_order_stat_check;
alter table "order" add constraint order_order_stat_check check (order_stat in ('Pending', 'Shipped', 'Delivered', 'Cancelled', 'Returned'));

-- each time the rider couldn't hand the package over
create table if not exists delivery_attempt (
  attempt_id    int generated by default as identity primary key,
  order_id      int not null references "order" (order_id) on delete cascade,
  reason        text not null,                     -- e.g. 'Customer not home'
  note          text,
  attempted_at  timestamptz not null default now()
);
create index if not exists delivery_attempt_order_id_idx on delivery_attempt (order_id);
alter table delivery_attempt enable row level security;

-- older orders: the fee was total minus the items, the courier is in the shipping_add text
update "order" o
set delivery_fee = greatest(0, o.total_amt - coalesce((select sum(sub_total) from order_item i where i.order_id = o.order_id), 0)),
    courier = substring(o.shipping_add from '\(Standard Delivery via ([^)]+)\)')
where o.courier is null and o.shipping_add like '%(Standard Delivery via %';
