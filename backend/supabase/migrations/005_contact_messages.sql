-- Messages from the Contact Us form. See SCHEMA_GAPS.md #29. Safe to run more than once.
create table if not exists contact_message (
  message_id  bigint generated by default as identity primary key,
  name        text not null,
  email       text not null,
  subject     text not null,
  message     text not null,
  ip_address  text,                               -- limits how many one visitor can send
  created_at  timestamptz not null default now()
);
create index if not exists contact_message_created_at_idx on contact_message (created_at desc);
alter table contact_message drop column if exists emailed;  -- only used while the site sent the emails itself

-- only the backend reads and writes this table
alter table contact_message enable row level security;
