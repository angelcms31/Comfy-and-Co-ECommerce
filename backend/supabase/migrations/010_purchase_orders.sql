-- Restock orders to suppliers. Safe to run more than once.
--
-- An admin orders items from a supplier (only products in that supplier's categories), then receives them:
-- good units go into prod_var.stocks, damaged ones become a defect_report (source 'receiving') tied to the order.
-- status: Ordered -> Partly received -> Received. Cancelled = the remaining units won't come (received ones stay).

create table if not exists purchase_order (
  po_id          int generated by default as identity primary key,
  supplier_id    int not null references supplier (supplier_id) on delete restrict,
  supplier_name  text not null,                       -- kept as it was when ordered
  status         text not null default 'Ordered' check (status in ('Ordered', 'Partly received', 'Received', 'Cancelled')),
  expected_date  date,
  notes          text,
  created_by     uuid references "user" (user_id) on delete set null,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  received_at    timestamptz                          -- when the last unit arrived
);

create table if not exists purchase_order_item (
  po_item_id     int generated by default as identity primary key,
  po_id          int not null references purchase_order (po_id) on delete cascade,
  prod_var_id    int references prod_var (prod_var_id) on delete set null,
  item_name      text not null,                       -- product + variant name, kept if the product is deleted
  sku            text not null,
  quantity       int not null check (quantity > 0),
  unit_cost      numeric(10, 2) check (unit_cost >= 0),   -- what the supplier charges, optional
  received_qty   int not null default 0 check (received_qty >= 0),   -- good units, already added to stock
  damaged_qty    int not null default 0 check (damaged_qty >= 0),    -- reported as item issues, never stocked
  check (received_qty + damaged_qty <= quantity)
);
create index if not exists purchase_order_supplier_idx on purchase_order (supplier_id);
create index if not exists purchase_order_created_idx on purchase_order (created_at desc);
create index if not exists purchase_order_item_po_idx on purchase_order_item (po_id);

-- a damaged unit found when a restock order arrives points back to that order
alter table defect_report add column if not exists po_id int references purchase_order (po_id) on delete set null;

alter table purchase_order enable row level security;
alter table purchase_order_item enable row level security;
